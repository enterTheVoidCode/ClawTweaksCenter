using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

namespace ClawTweaksCenter.Library
{
    /// <summary>One thing the user could add to the Misc tab.</summary>
    public sealed class AppCandidate
    {
        public string Name { get; set; }

        /// <summary>Absolute path, where it could be resolved. Null for packaged apps and for the
        /// opaque ProgIDs the Start menu hands out (<c>AutoHotkey.AutoHotkey</c>,
        /// <c>Microsoft.AutoGenerated.{…}</c>) - those have no path anywhere to find.</summary>
        public string Exe { get; set; }

        public string Args { get; set; }

        /// <summary>Start menu AppID, for everything that has to be activated through the shell.</summary>
        public string Aumid { get; set; }

        /// <summary>"Start menu", "Desktop" or "Startup". Shown next to the name so two entries with
        /// the same title can be told apart.</summary>
        public string Origin { get; set; }

        /// <summary>What identity means here: the target, not the name. The same tool reached from a
        /// desktop shortcut and from the Start menu is one tool.</summary>
        public string DedupeKey =>
            !string.IsNullOrEmpty(Exe) ? Exe.ToLowerInvariant() : "aumid:" + (Aumid ?? string.Empty).ToLowerInvariant();
    }

    /// <summary>
    /// Everything on this machine that could be added to the Misc tab, gathered from the places that
    /// already hold a curated list.
    ///
    /// MEASURED, and the measurement decided the design. Recursing the program folders for *.exe was
    /// the obvious idea and is the wrong one: 67 s for 3065 executables on this machine, and limiting
    /// the depth to three and filtering by name and size still leaves 87 - of which the survivors read
    /// <c>git-lfs, pdftotext, bash, gpg, mintty, rvim, sh, vim, vimdiff, fossilize-replay,
    /// virtualdisplay_probe</c> with <c>Vortex</c>, <c>Moonlight</c> and <c>chiaki</c> buried among
    /// them. No filename rule separates "vim" from "chiaki"; both are short names over a megabyte.
    ///
    /// <c>Get-StartApps</c> answers the same question properly in 2.9 s: 236 entries, packaged AND
    /// classic in ONE call, and the names come from the installers rather than from a basename -
    /// "Moonlight", "MSI Center M", "Forza Horizon 6". Desktop and Startup shortcuts are added because
    /// they are the user's own picks and a tool installed without a Start menu entry appears nowhere
    /// else.
    /// </summary>
    public static class AppInventory
    {
        /// <summary>Field separator for the PowerShell output. A control character, because an app
        /// name may legitimately hold a pipe, a tab or a comma, and a separator that can appear in
        /// the data turns one odd entry into a parse failure.</summary>
        private const char Sep = '\u0001';

        public static Task<IReadOnlyList<AppCandidate>> ScanAsync(CancellationToken ct)
            => Task.Run<IReadOnlyList<AppCandidate>>(() => Scan(ct), ct);

        private static IReadOnlyList<AppCandidate> Scan(CancellationToken ct)
        {
            var found = new List<AppCandidate>();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            string output = RunPowerShell(BuildCommand(), 60000);
            if (string.IsNullOrWhiteSpace(output)) return found;

            foreach (string line in output.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries))
            {
                ct.ThrowIfCancellationRequested();

                string[] f = line.Split(Sep);
                if (f.Length < 4) continue;

                string origin = f[1].Trim();
                string name = f[2].Trim();
                string target = f[3].Trim();
                string args = f.Length > 4 ? f[4].Trim() : string.Empty;
                if (name.Length == 0 || target.Length == 0) continue;
                if (IsBlacklisted(name)) continue;

                var candidate = f[0] == "S" ? FromStartApp(name, target, origin) : FromShortcut(name, target, args, origin);
                if (candidate == null) continue;
                if (!seen.Add(candidate.DedupeKey)) continue;

                found.Add(candidate);
            }

            found.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));
            return found;
        }

        /// <summary>
        /// Words that disqualify an entry by its DISPLAYED NAME.
        ///
        /// "install" alone covers both directions - "Uninstall X" contains it too, which is what makes
        /// one substring enough. Measured on this machine: 9 of the 236 Start menu entries matched,
        /// and all 9 really were installers or uninstallers (Visual Studio Installer, Uninstall USBip,
        /// OptiScaler_Installer_v0.3.6, ...).
        ///
        /// Matched against the name the USER SEES, deliberately not against the exe path as well: a
        /// perfectly good tool that happens to live in a folder called "installer" should still be
        /// offerable, and a filter that hides things for reasons invisible on screen is the kind that
        /// gets reported as "my tool is missing".
        /// </summary>
        private static readonly string[] NameBlacklist = { "install" };

        private static bool IsBlacklisted(string name)
        {
            foreach (string word in NameBlacklist)
                if (name.IndexOf(word, StringComparison.OrdinalIgnoreCase) >= 0) return true;
            return false;
        }

        /// <summary>
        /// One <c>Get-StartApps</c> row. The AppID comes in four shapes, verified on this machine:
        /// <c>PFN!AppId</c> (packaged), <c>{KnownFolderGuid}\rel\path.exe</c>, a plain absolute path,
        /// and <c>steam://rungameid/N</c>. A fifth group is opaque - <c>AutoHotkey.AutoHotkey</c>,
        /// <c>com.squirrel.…</c>, <c>Microsoft.AutoGenerated.{…}</c> - and those keep the AppID and
        /// are activated through the shell.
        /// </summary>
        private static AppCandidate FromStartApp(string name, string appId, string origin)
        {
            // Steam entries are games, and every one of them is already in the Steam tab. Offering
            // them here would let the user build a second, worse copy of their own library.
            if (appId.StartsWith("steam://", StringComparison.OrdinalIgnoreCase)) return null;
            if (appId.StartsWith("http://", StringComparison.OrdinalIgnoreCase)) return null;
            if (appId.StartsWith("https://", StringComparison.OrdinalIgnoreCase)) return null;

            string exe = null;
            if (appId.StartsWith("{", StringComparison.Ordinal))
            {
                exe = ResolveKnownFolderPath(appId);
            }
            else if (appId.Length > 2 && appId[1] == ':' && appId.IndexOf('\\') > 0)
            {
                exe = appId;
            }

            if (exe != null)
            {
                // Help files and shortcuts to documents come through the same list as the programs.
                if (!exe.EndsWith(".exe", StringComparison.OrdinalIgnoreCase)) return null;
                if (!File.Exists(exe)) return null;
                return new AppCandidate { Name = name, Exe = exe, Origin = origin };
            }

            return new AppCandidate { Name = name, Aumid = appId, Origin = origin };
        }

        private static AppCandidate FromShortcut(string name, string target, string args, string origin)
        {
            if (!target.EndsWith(".exe", StringComparison.OrdinalIgnoreCase)) return null;
            if (!File.Exists(target)) return null;
            return new AppCandidate { Name = name, Exe = target, Args = args, Origin = origin };
        }

        /// <summary>
        /// Turns <c>{6D809377-…}\7-Zip\7zFM.exe</c> into a real path.
        ///
        /// Resolved through the API rather than from a table of GUIDs: the folders are per-user and
        /// redirectable, and a hard-coded <c>C:\Program Files</c> is wrong on exactly the machines
        /// where it matters. Measured distribution here: 24 entries under Program Files (x86), 21
        /// under System32, 20 under Program Files, plus a handful elsewhere.
        /// </summary>
        private static string ResolveKnownFolderPath(string appId)
        {
            int close = appId.IndexOf('}');
            if (close <= 0 || close >= appId.Length - 1) return null;

            string guidText = appId.Substring(1, close - 1);
            string relative = appId.Substring(close + 1).TrimStart('\\');
            if (relative.Length == 0) return null;
            if (!Guid.TryParse(guidText, out Guid folderId)) return null;

            IntPtr buffer = IntPtr.Zero;
            try
            {
                if (SHGetKnownFolderPath(ref folderId, 0, IntPtr.Zero, out buffer) != 0) return null;
                string root = Marshal.PtrToStringUni(buffer);
                if (string.IsNullOrEmpty(root)) return null;
                return Path.Combine(root, relative);
            }
            catch { return null; }
            finally { if (buffer != IntPtr.Zero) Marshal.FreeCoTaskMem(buffer); }
        }

        [DllImport("shell32.dll", CharSet = CharSet.Unicode)]
        private static extern int SHGetKnownFolderPath(ref Guid rfid, uint flags, IntPtr token, out IntPtr path);

        /// <summary>
        /// The whole harvest as one PowerShell command.
        ///
        /// ONE process, not four. Starting Windows PowerShell costs about a second before it runs a
        /// single statement, so splitting this per source would spend more time on process startup
        /// than on the work. Single quotes throughout - the command is embedded in a double-quoted
        /// -Command argument.
        /// </summary>
        private static string BuildCommand()
        {
            var sb = new StringBuilder();
            sb.Append("$ErrorActionPreference='SilentlyContinue';");
            sb.Append("$s=[char]1;");
            sb.Append("Get-StartApps | ForEach-Object { 'S'+$s+'Start menu'+$s+$_.Name+$s+$_.AppID+$s };");
            sb.Append("$w=New-Object -ComObject WScript.Shell;");
            // A HASHTABLE, not an array of pairs. @(@(a,b),@(c,d)) is flattened by PowerShell into
            // eight loose strings, so $d[0] indexes a CHARACTER and Test-Path is handed "C". It fails
            // silently and harvests nothing - measured: 236 Start menu rows and zero shortcuts.
            sb.Append("$dirs=@{};");
            sb.Append("$dirs[$env:USERPROFILE+'\\Desktop']='Desktop';");
            sb.Append("$dirs[$env:PUBLIC+'\\Desktop']='Desktop';");
            sb.Append("$dirs[$env:APPDATA+'\\Microsoft\\Windows\\Start Menu\\Programs\\Startup']='Startup';");
            sb.Append("$dirs[$env:ProgramData+'\\Microsoft\\Windows\\Start Menu\\Programs\\Startup']='Startup';");
            sb.Append("foreach($p in $dirs.Keys){ if(Test-Path $p){ Get-ChildItem $p -Filter *.lnk | ForEach-Object {");
            sb.Append(" $k=$w.CreateShortcut($_.FullName);");
            sb.Append(" if($k.TargetPath){ 'L'+$s+$dirs[$p]+$s+$_.BaseName+$s+$k.TargetPath+$s+$k.Arguments } } } }");
            return sb.ToString();
        }

        /// <summary>Windows PowerShell by full path, the same instrument XboxSource uses. Needs no
        /// elevation and is present on every Windows this runs on.</summary>
        private static string RunPowerShell(string command, int timeoutMs)
        {
            try
            {
                string winPs = Path.Combine(Environment.SystemDirectory, "WindowsPowerShell", "v1.0", "powershell.exe");
                var psi = new ProcessStartInfo
                {
                    FileName = File.Exists(winPs) ? winPs : "powershell.exe",
                    Arguments = "-NoProfile -NonInteractive -ExecutionPolicy Bypass -Command \"" +
                                command.Replace("\"", "\\\"") + "\"",
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    StandardOutputEncoding = Encoding.UTF8,
                };
                using var proc = Process.Start(psi);
                if (proc == null) return null;
                string outp = proc.StandardOutput.ReadToEnd();
                proc.StandardError.ReadToEnd();
                if (!proc.WaitForExit(timeoutMs)) { try { proc.Kill(); } catch { } return null; }
                return outp;
            }
            catch { return null; }
        }
    }
}
